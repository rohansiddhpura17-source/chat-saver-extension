// Packages the production build as a loadable unpacked Chrome extension.
// Run after `npm run build`: copies the manifest and the extension files
// (which live at the project root, where manifest.json references them)
// into dist/, so dist/ itself is what Chrome loads via
// chrome://extensions -> Developer mode -> Load unpacked.
// Re-run after every build: `vite build` empties dist/ first.
//
// Root sync (2026-11-10): the built popup.html and assets/ are ALSO copied
// back to the project root. The extension on ROHAN's Mac was loaded from the
// project root instead of dist/, and a root load can only show the popup if
// the root popup.html is the built file (the source popup.src.html points at
// /src/main.tsx, which Chrome serves as application/octet-stream, so the
// popup came up blank). Keeping the root in sync means the extension works
// whichever folder it was loaded from. Root popup.html and root assets/ are
// GENERATED by this script — do not edit them by hand; the source is
// popup.src.html. The sync clears root assets/ first so a stale hashed
// bundle from an older build can never linger.
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')

const files = ['manifest.json', 'background.js', 'content.js', 'content.css']
const dirs = ['icons']

for (const file of files) {
  const source = join(root, file)
  if (!existsSync(source)) {
    console.error(`package-extension: missing ${file} at project root`)
    process.exit(1)
  }
  cpSync(source, join(dist, file))
}

for (const dir of dirs) {
  const source = join(root, dir)
  if (!existsSync(source) || !statSync(source).isDirectory()) {
    console.error(`package-extension: missing ${dir}/ at project root`)
    process.exit(1)
  }
  mkdirSync(join(dist, dir), { recursive: true })
  for (const entry of readdirSync(source)) {
    cpSync(join(source, entry), join(dist, dir, entry))
  }
}

console.log('package-extension: dist/ is ready to load unpacked in Chrome.')
console.log(`  manifest.json, ${files.slice(1).join(', ')}, icons/ (${readdirSync(join(root, 'icons')).join(', ')})`)

// Root sync: keep a root-loaded copy of the extension working (see the
// header comment). dist/popup.html is the built popup; root assets/ holds
// the hashed bundle it references.
//
// Vite names the built popup after its input file (popup.src.html), while
// the manifest expects popup.html, so rename it in dist/ first.
const builtPopupSrc = join(dist, 'popup.src.html')
if (!existsSync(builtPopupSrc)) {
  console.error('package-extension: missing dist/popup.src.html after build')
  process.exit(1)
}
cpSync(builtPopupSrc, join(dist, 'popup.html'))
rmSync(builtPopupSrc, { force: true })

const builtPopup = join(dist, 'popup.html')
if (!existsSync(builtPopup)) {
  console.error('package-extension: missing dist/popup.html after build')
  process.exit(1)
}
cpSync(builtPopup, join(root, 'popup.html'))
const distAssets = join(dist, 'assets')
const rootAssets = join(root, 'assets')
rmSync(rootAssets, { force: true, recursive: true })
mkdirSync(rootAssets, { recursive: true })
for (const entry of readdirSync(distAssets)) {
  cpSync(join(distAssets, entry), join(rootAssets, entry))
}
console.log(`  root sync: popup.html + assets/ (${readdirSync(rootAssets).join(', ')}) copied to project root`)
